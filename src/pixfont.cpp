// Descenders (g j p q y) need two rows below the baseline, so those glyphs are 9 rows tall.
static const struct { char ch; unsigned short col[5]; } kDesc[] = {
    { 'g', { 0x098, 0x124, 0x124, 0x124, 0x0F8 } },
    { 'j', { 0x080, 0x100, 0x100, 0x0FA, 0x000 } },
    { 'p', { 0x1FC, 0x044, 0x044, 0x044, 0x038 } },
    { 'q', { 0x038, 0x044, 0x044, 0x044, 0x1FC } },
    { 'y', { 0x09C, 0x120, 0x120, 0x120, 0x0FC } },
};

static Texture2D g_atlas{};
static unsigned short g_cols[95][5];
static int g_first[95], g_last[95], g_rows[95];

void Init() {
    for (int g = 0; g < 95; g++) for (int c = 0; c < 5; c++) g_cols[g][c] = kFont[g][c];
    for (const auto& d : kDesc) for (int c = 0; c < 5; c++) g_cols[d.ch - 32][c] = d.col[c];
    const int cw = 8, ch = 10, cols = 16, rows = 6;
    Image img = GenImageColor(cols * cw, rows * ch, Color{ 0, 0, 0, 0 });
    for (int g = 0; g < 95; g++) {
        int f = 4, l = 0, maxBit = 0;
        for (int c = 0; c < 5; c++) {
            if (g_cols[g][c] == 0) continue;
            f = std::min(f, c); l = std::max(l, c);
            for (int r = 0; r < 9; r++) {
                if (g_cols[g][c] & (1 << r)) { ImageDrawPixel(&img, (g % cols) * cw + c, (g / cols) * ch + r, WHITE); maxBit = std::max(maxBit, r); }
            }
        }
        if (l < f) { f = 0; l = 2; }          // blank glyph (space): a three-pixel gap
        g_first[g] = f; g_last[g] = l;
        g_rows[g] = maxBit >= 7 ? 9 : 7;
    }
    g_atlas = LoadTextureFromImage(img);
    UnloadImage(img);
    SetTextureFilter(g_atlas, TEXTURE_FILTER_POINT);
}

void Shutdown() { if (g_atlas.id) UnloadTexture(g_atlas); g_atlas = Texture2D{}; }

int Index(int cp) {
    if (cp == '\t') cp = ' ';
    if (cp >= 32 && cp <= 126) return cp - 32;
    switch (cp) {
        case 0xA0: return 0;
        case 0x2013: case 0x2014: return '-' - 32;
        case 0x2018: case 0x2019: return '\'' - 32;
        case 0x201C: case 0x201D: return '"' - 32;
        case 0x2022: return '*' - 32;
        case 0x2026: return '.' - 32;
        case 0x2190: case 0x2264: return '<' - 32;
        case 0x2192: case 0x2265: return '>' - 32;
        case 0x2191: return '^' - 32;
        case 0x2193: case 0x221A: return 'v' - 32;
        case 0x2260: return '=' - 32;
        case 0x2122: return 'T' - 32;
        case 0xD7: return 'x' - 32;
        default: return '?' - 32;
    }
}

int Advance(int g, bool mono) {
    if (mono) return 6;
    if (g == 0) return 3;
    return g_last[g] - g_first[g] + 1 + 1;
}

void Draw(int g, float x, float y, float pix, int k, Color c, bool mono, bool bold, bool italic) {
    if (g <= 0 || g > 94) return;
    int f = mono ? 0 : g_first[g], l = mono ? 4 : g_last[g];
    int w = l - f + 1, h = g_rows[g];
    float u = pix * (float)k;
    float sx = (float)((g % 16) * 8 + f), sy = (float)((g / 16) * 10);
    for (int pass = 0; pass < (bold ? 2 : 1); pass++) {
        float ox = x + pass * u;
        if (italic) {
            // the top three rows lean one pixel to the right
            DrawTexturePro(g_atlas, Rectangle{ sx, sy, (float)w, 3.f }, Rectangle{ ox + u, y, w * u, 3 * u }, Vector2{ 0, 0 }, 0, c);
            DrawTexturePro(g_atlas, Rectangle{ sx, sy + 3.f, (float)w, (float)(h - 3) }, Rectangle{ ox, y + 3 * u, w * u, (h - 3) * u }, Vector2{ 0, 0 }, 0, c);
        } else {
            DrawTexturePro(g_atlas, Rectangle{ sx, sy, (float)w, (float)h }, Rectangle{ ox, y, w * u, h * u }, Vector2{ 0, 0 }, 0, c);
        }
    }
}

